type TranslationContextValue = {
  language: Language;
  setLanguage: (language: Language) => Promise<void>;
  locale: string;
  t: (key: string, values?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<TranslationContextValue>({
  language: "pt",
  setLanguage: async () => {},
  locale: "pt-BR",
  t: (key) => key,
});

const LOCALES: Record<Language, string> = {
  pt: "pt-BR",
  en: "en-US",
  es: "es-ES",
  ja: "ja-JP",
};

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("pt");

  useEffect(() => {
    AsyncStorage.getItem(LANGUAGE_KEY)
      .then((savedLanguage) => {
        if (
          savedLanguage === "pt" ||
          savedLanguage === "en" ||
          savedLanguage === "es" ||
          savedLanguage === "ja"
        ) {
          setLanguageState(savedLanguage);
        }
      })
      .catch((error) => {
        console.log("Erro ao carregar idioma:", error);
      });
  }, []);

  const setLanguage = useCallback(async (nextLanguage: Language) => {
    try {
      await AsyncStorage.setItem(LANGUAGE_KEY, nextLanguage);
      setLanguageState(nextLanguage);
    } catch (error) {
      console.log("Erro ao salvar idioma:", error);
    }
  }, []);

  const t = useCallback(
    (key: string, values?: Record<string, string | number>) => {
      let translated =
        language === "pt" ? key : translations[language][key] || key;
      if (values) {
        for (const [name, value] of Object.entries(values)) {
          translated = translated.replaceAll(`{${name}}`, String(value));
        }
      }
      return translated;
    },
    [language]
  );

  const contextValue = useMemo(
    () => ({ language, setLanguage, locale: LOCALES[language], t }),
    [language, setLanguage, t]
  );

  return (
    <LanguageContext.Provider value={contextValue}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
