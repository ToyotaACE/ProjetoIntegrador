type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string, values?: Record<string, string | number>) => string;
  dateLocale: Locale;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function readLanguage(): Language {
  const saved = localStorage.getItem(LANGUAGE_KEY);
  return saved === "en" || saved === "es" || saved === "ja" ? saved : "pt";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(readLanguage);

  useEffect(() => {
    localStorage.setItem(LANGUAGE_KEY, language);
    document.documentElement.lang =
      language === "pt" ? "pt-BR" : language === "ja" ? "ja" : language;
  }, [language]);

  const t = useCallback(
    (text: string, values?: Record<string, string | number>) => {
      const translated =
        language === "pt"
          ? text
          : orderMessages[language][text] || messages[language][text] || text;
      return translated.replace(/\{(\w+)\}/g, (match, key: string) =>
        values && key in values ? String(values[key]) : match
      );
    },
    [language]
  );

  const dateLocale =
    language === "en" ? enUS : language === "es" ? es : language === "ja" ? ja : ptBR;

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, dateLocale }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}
